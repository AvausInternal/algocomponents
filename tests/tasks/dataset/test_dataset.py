from algocomponents.tasks import Dataset, Feature, FeatureBase, SQLPipeline, SQLTask


# Define class here so finding sql folder is easier
class SimpleFeatureBase(FeatureBase):
    """An example featurebase that contains user-product combinations"""

    output_primary_keys = [
        "user_id",
        "product_id",
    ]
    output_columns_created = []


# Define class here so finding sql folder is easier
class SimpleFeatureOne(Feature):
    """Feature that uses the featurebase as an input.

    The feature produces features on the user level.
    """

    input_columns = [
        "user_id",
        "product_id",
    ]
    output_primary_keys = [
        "user_id",
    ]
    output_columns_created = [
        "n_products_bought",
        "n_distinct_products_bought",
    ]


class SimpleFeatureTwo(Feature):
    """Feature that uses a prexisting table as input

    The feature produces features on the product level. The input
    table is generated by the prepare_existing_table fixture
    """

    input_columns = [
        "product_id",
        "product_price",
        "product_weight",
    ]
    output_primary_keys = [
        "product_id",
    ]
    output_columns_created = [
        "price_per_kg",
        "product_price",
        "product_weight",
    ]


class IncorrectPrimaryKeyFeature(Feature):
    """A feature with primary keys that do not exist in any table"""

    input_columns = ["incorrectly_named_product_id"]
    output_primary_keys = ["incorrectly_named_product_id"]
    output_columns_created = ["incorrectly_named_output"]


# changing scope to 'function' fixtures will run for each methodcall seperately.
@pytest.fixture(scope="class", name="prepared_table")
def prepare_existing_table():
    """Prepares a dummy table with product level features

    The table contains the columns product_id, product_price,
    and product_weight. When the fixture is directly passed it yields the name
    of the table it created.

    Yields:
        yield formatted_table_name
    """

    # setup:
    sql_adapter = LocalSqliteAdapter()
    global_config_path = os.path.join("tests", "tasks", "dataset", "dataset_config")
    dir_path = os.path.join("tests", "tasks", "dataset", "preparation_queries")

    pipeline = SQLPipeline(
        global_config_dir=global_config_path,
        sql_folder=dir_path,
        sql_folder_relative_path=False,
        sql_adapter=sql_adapter,
    )
    pipeline.start()

    # config variable defines the output table name
    table_name = pipeline.config[pipeline.section]["pre_existing_table"]
    formatted_table_name = table_name.format(**pipeline.config[pipeline.section])
    sql_adapter.connect()
    assert sql_adapter.table_exists(formatted_table_name)

    yield formatted_table_name

    # teardown:
    sql_adapter.connect()
    SQLTask(
        sql_string=f"DROP TABLE IF EXISTS {formatted_table_name};",
        sql_adapter=sql_adapter,
    ).start()
    assert sql_adapter.table_exists(formatted_table_name) is False


